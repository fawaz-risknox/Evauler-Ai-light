export default function FAQSection() {
  const [activeCategory, setActiveCategory] = useState('score');
  const [openIndexes, setOpenIndexes] = useState([0]);

  const toggleQuestion = (index) => {
    setOpenIndexes((prev) =>
      prev.includes(index) ? prev.filter((i) => i !== index) : [...prev, index]
    );
  };

  const currentQuestions = FAQ_DATA[activeCategory] || [];

  return (
    <section id="faq" className="py-20 sm:py-28 bg-slate-50/60 border-t border-slate-200/80 ambient-wash-f">
      <div className="max-w-4xl mx-auto px-4 sm:px-6 lg:px-8">
        
        {/* Header */}
        <div className="text-center mb-8 sm:mb-10">
          <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-blue-50 border border-blue-200 text-blue-700 text-xs font-semibold mb-3">
            <HelpCircle size={14} />
            <span>Questions and answers</span>
          </div>
          <h2 className="text-3xl sm:text-4xl lg:text-5xl font-extrabold text-slate-900 tracking-tight">
            Frequently asked questions
          </h2>
          <p className="mt-3 text-base text-slate-600">
            Everything you need to know about the scoring methodology, valuation formulas, and privacy.
          </p>
        </div>

        {/* Category switcher */}
        <div className="flex items-center justify-center gap-1.5 mb-6 overflow-x-auto pb-1">
          {Object.entries(CATEGORIES).map(([key, label]) => (
            <button
              key={key}
              type="button"
              onClick={() => {
                setActiveCategory(key);
                setOpenIndexes([0]);
              }}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all whitespace-nowrap ${
                activeCategory === key
                  ? 'bg-blue-600 text-white shadow-xs'
                  : 'bg-white hover:bg-slate-100 text-slate-700 border border-slate-200'
              }`}
            >
              {label}
            </button>
          ))}
        </div>

        {/* Accordion list */}
        <div className="space-y-2">
          {currentQuestions.map((item, idx) => {
            const isOpen = openIndexes.includes(idx);
            return (
              <div
                key={item.q}
                className="bg-white rounded-xl border border-slate-200 overflow-hidden shadow-xs transition-all"
              >
                <button
                  type="button"
                  onClick={() => toggleQuestion(idx)}
                  className="w-full py-3 px-4 sm:px-5 text-left flex items-center justify-between gap-3 text-xs sm:text-sm font-bold text-slate-900 hover:text-blue-600 transition-colors"
                >
                  <span>{item.q}</span>
                  <ChevronDown
                    size={16}
                    className={`text-slate-400 shrink-0 transition-transform duration-200 ${
                      isOpen ? 'rotate-180 text-blue-600' : ''
                    }`}
                  />
                </button>
                {isOpen && (
                  <div className="px-4 sm:px-5 pb-3.5 pt-0.5 text-xs text-slate-600 leading-relaxed border-t border-slate-100 animate-in fade-in duration-150">
                    {item.a}
                  </div>
                )}
              </div>
            );
          })}
        </div>

      </div>
    </section>
  );
}

